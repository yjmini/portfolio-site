import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdir, writeFile } from 'node:fs/promises'
const base = process.env.PORTFOLIO_URL || 'http://127.0.0.1:4187/'
const out = process.env.QA_OUTPUT || '/tmp/portfolio-kinetic-qa'
await mkdir(out, {recursive:true})
const browser = await chromium.launch({args:['--enable-unsafe-swiftshader']})
const checks = [], errors = []
try {
 const context = await browser.newContext({viewport:{width:1440,height:1000}})
 const page = await context.newPage()
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(`${base}#/lab-archive`)
 await expect(page.locator('.kinetic-home')).toBeVisible()
 await expect(page.getByRole('heading',{level:1})).toContainText('MACHINES')
 await expect(page.locator('.particle-stage')).toHaveAttribute('data-state','ready',{timeout:20000})
 await page.waitForTimeout(1400)
 await expect(page.locator('.kh-title-wrap')).toHaveCSS('opacity','1')
 await expect(page.locator('.kh-outro')).toHaveCSS('opacity','0')
 await page.screenshot({path:`${out}/hero.png`})
 checks.push('Full-screen kinetic home and generative sculpture load')
 const reveal = page.locator('.kh-reveal')
 await page.mouse.move(240,360); await page.waitForTimeout(150)
 const before = await reveal.evaluate(el=>getComputedStyle(el).clipPath)
 await page.mouse.move(800,420); await page.waitForTimeout(150)
 expect(await reveal.evaluate(el=>getComputedStyle(el).clipPath)).not.toBe(before)
 checks.push('Pointer moves the reveal lens across the entire hero')
 await page.getByRole('button',{name:'Wave',exact:true}).click()
 await expect(page.getByRole('button',{name:'Wave',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Grid',exact:true}).click()
 await expect(page.getByRole('button',{name:'Grid',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Orbit',exact:true}).click()
 checks.push('Sculpture mode controls respond')
 const initialTransform = await page.locator('.kh-title-wrap').evaluate(el=>getComputedStyle(el).transform)
 await page.evaluate(()=>window.scrollTo({top:innerHeight*.65,behavior:'instant'}));await page.waitForTimeout(300)
 expect(await page.locator('.kh-title-wrap').evaluate(el=>getComputedStyle(el).transform)).not.toBe(initialTransform)
 expect(Math.abs(await page.locator('.kh-viewport').evaluate(el=>el.getBoundingClientRect().top))).toBeLessThan(2)
 checks.push('Scroll pins the hero and changes its actual composition')
 await page.locator('#kinetic-projects').scrollIntoViewIfNeeded();await page.waitForTimeout(500)
 await expect(page.locator('#kinetic-projects a[href^="#/projects/"]').first()).toHaveAttribute('href',/#\/projects\/.+/)
 await page.screenshot({path:`${out}/gallery.png`})
 checks.push('Interactive gallery preserves genuine project detail links')
 await page.locator('#kinetic-lab').scrollIntoViewIfNeeded()
 const chip=page.getByRole('button',{name:'ROS2 옮기기'})
 await chip.focus(); await page.keyboard.press('ArrowRight')
 await expect(chip).toHaveAttribute('data-moved','true')
 await page.getByRole('button',{name:'플레이그라운드 초기화'}).click()
 await expect(page.getByRole('button',{name:'ROS2 옮기기'})).toHaveAttribute('data-moved','false')
 await page.screenshot({path:`${out}/playground.png`})
 checks.push('Skill playground keyboard manipulation and reset')
 for(const width of [360,390,768,1024]) {
  await page.setViewportSize({width,height:900});await page.goto(`${base}#/lab-archive`);await page.waitForTimeout(700)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
  if(width===390) await page.screenshot({path:`${out}/mobile.png`,fullPage:true})
  checks.push(`Home width ${width}: no horizontal overflow`)
 }
 await page.emulateMedia({reducedMotion:'reduce'});await page.goto(`${base}#/lab-archive`)
 await expect(page.getByRole('button',{name:'Orbit',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'프로젝트 바로 보기'}).click()
 await expect(page.locator('#kinetic-projects')).toBeInViewport()
 checks.push('Reduced-motion interaction and direct project jump')
 for(const route of ['/projects','/about','/work','/resume','/contact','/copyright','/portfolio-pdf']){
  await page.goto(`${base}#${route}`)
  await expect(page.locator('main')).toBeVisible()
 }
 checks.push('Existing routes and PDF still render')
 expect(errors).toEqual([])
 await page.goto(`${base}#/lab-archive`); await page.waitForTimeout(700)
 const axe=await new AxeBuilder({page}).include('main').withTags(['wcag2a','wcag2aa']).analyze()
 await writeFile(`${out}/axe.json`,JSON.stringify(axe.violations,null,2))
 expect(axe.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)}))).toEqual([])
 checks.push('Main WCAG A/AA automated scan and no uncaught JavaScript errors')
 await writeFile(`${out}/report.json`,JSON.stringify({checks,errors},null,2))
 console.log(checks.map(c=>`PASS ${c}`).join('\n'))
}finally{await browser.close()}
